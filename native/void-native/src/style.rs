//! Style interning: C# registers each distinct layout style once and refers to it by handle afterwards.
//!
//! The value types and enums here are the source of truth for their C# counterparts, which csbindgen generates
//! (see `build.rs`). They keep the names of the managed `Taffy.dll` types they replace, so code moving over only
//! needs a different `using`. Field names are PascalCase where the C# API has always used them that way.

#![allow(non_snake_case)]

use taffy::prelude::*;
use taffy::style::{MaxTrackSizingFunction, MinTrackSizingFunction, Overflow};

/// Implements a checked conversion from the raw `u32` C# sends. Enum values cross the boundary as plain
/// numbers, so a bad cast on the C# side becomes an error instead of undefined behaviour.
///
/// The enums themselves are written out (not generated by this macro) because csbindgen cannot see inside
/// macro invocations.
macro_rules! from_raw {
    ($name:ident { $($variant:ident),* $(,)? }) => {
        impl $name {
            fn from_raw(field: &str, raw: u32) -> R<Self> {
                $(if raw == Self::$variant as u32 { return Ok(Self::$variant); })*
                Err(format!("{field}: unknown {} value {raw}", stringify!($name)))
            }
        }
    };
}

